export type Skill = {
  id?: string;
  name: string;
  category?: string;
  is_verified?: boolean;
  proficiency?: "beginner" | "intermediate" | "advanced";
  importance?: "required" | "preferred";
};
export type Breakdown = {
  cosine: number;
  cosine_score: number;
  coverage: number;
  final_score: number;
  band: "STRONG" | "MODERATE" | "WEAK";
  matched_skills: string[];
  missing_skills: string[];
  model: string;
  version: string;
};
export type Role = {
  id: string;
  title: string;
  description: string;
  slots: number;
  filled_count: number;
  skills: Skill[];
};
export type Profile = {
  id: string;
  display_name: string;
  headline: string;
  bio: string;
  university: string;
  interests: string;
  avatar_url: string | null;
  avatar_key: string | null;
  is_member: boolean;
  is_team_lead: boolean;
  onboarding_complete: boolean;
  is_demo: boolean;
  revision: number;
  skills: Skill[];
};
export type Project = {
  id: string;
  owner_id: string;
  title: string;
  description: string;
  category: string;
  tags: string[];
  commitment: string;
  duration: string;
  team_size: number;
  status: string;
  auto_approve_strong_matches: boolean;
  revision: number;
  roles: Role[];
  lead_name?: string;
  role_title?: string;
  open_roles?: { title: string; available: number }[];
  role_id?: string;
  breakdown?: Breakdown;
  is_demo: boolean;
};
export type MatchRecord = {
  id: string;
  project_id: string;
  role_id: string | null;
  applicant_id?: string;
  invitee_id?: string;
  status: string;
  message: string;
  band: string;
  final_score: number;
  breakdown: Breakdown;
  created_at: string;
  projects: { title: string };
  project_roles: { title: string } | null;
  profiles?: { display_name: string; headline: string };
};
