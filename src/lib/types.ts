export type Skill = {
  id?: string;
  name: string;
  category?: string;
  is_verified?: boolean;
  proficiency?: "beginner" | "intermediate" | "advanced";
  importance?: "required" | "preferred";
};
export type SkillOverlap = {
  matched_skills: string[];
  missing_skills: string[];
};
export type Role = {
  id: string;
  title: string;
  description: string;
  slots: number;
  filled_count: number;
  domains?: string[];
  skills: Skill[];
  match?:import('./matching/roleMatch').RoleMatch;
};
export type Profile = {
  id: string;
  display_name: string;
  headline: string;
  bio: string;
  university: string;
  interests: string;
  avatar_url: string | null;
  avatar_key: string | null;
  is_member: boolean;
  is_team_lead: boolean;
  onboarding_complete: boolean;
  is_demo: boolean;
  revision: number;
  domains?: string[];
  skills: Skill[];
};
export type Project = {
  id: string;
  owner_id: string;
  title: string;
  description: string;
  category: string;
  domains?: string[];
  sort_key?: number;
  tags: string[];
  commitment: string;
  duration: string;
  team_size: number;
  status: string;
  revision: number;
  roles: Role[];
  lead_name?: string;
  role_title?: string;
  open_roles?: { title: string; available: number }[];
  role_id?: string;
  is_demo: boolean;
};
export type MatchRecord = {
  id: string;
  project_id: string;
  role_id: string | null;
  applicant_id?: string;
  invitee_id?: string;
  status: string;
  message: string;
  breakdown: SkillOverlap;
  matchPercent:number|null;
  calibrationVersion:string|null;
  created_at: string;
  projects: { title: string };
  project_roles: { title: string } | null;
  profiles?: { display_name: string; headline: string };
};
